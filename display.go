func (p *ppu) GenBuffer() []byte {
	buffer := make([]byte, 256*128*4)

	for bank := uint16(0); bank < 2; bank++ {
		bankOffset := bank * 0x1000

		for tileIndex := uint16(0); tileIndex < 256; tileIndex++ {
			tilePix := p.DecodeTile(tileIndex, bankOffset)

			tileX := int(tileIndex % 16)
			tileY := int(tileIndex / 16)

			screenX := int(bank*128) + (tileX * 8)
			screenY := tileY * 8

			p.renderTileToBuffer(buffer, tilePix, screenX, screenY)

		}
	}

	return buffer
}

func (p *ppu) renderTileToBuffer(buffer []byte, tilePix [8][8]uint8, screenX int, screenY int) {
	for y, rowPix := range tilePix {
		for x, color := range rowPix {
			targetX := screenX + x
			targetY := screenY + y

			RGBA := Universal_pallete[color]

			if targetX >= 0 && targetX < 256 && targetY >= 0 && targetY < 128 {
				idx := (targetY*256 + targetX) * 4
				buffer[idx] = RGBA[0]
				buffer[idx+1] = RGBA[1]
				buffer[idx+2] = RGBA[2]
				buffer[idx+3] = RGBA[3]
			}

		}
	}
}

func (p *ppu) DrawNameTable(buffer []byte) {
	for i := range 960 {
		tileIndex := p.mem.Vram[i]

		tileX := i & 32
		tileY := i / 32

		tileData := p.DecodeTile(uint16(tileIndex), 0x0000)

		p.renderTileToBuffer(buffer, tileData, tileX*8, tileY*8)
	}
}
